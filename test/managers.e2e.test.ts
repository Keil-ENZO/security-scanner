import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterAll, describe, expect, it } from 'vitest'
import { applyBumps, detectManager, type Manager, managerCommands } from '../server/utils/managers'
import { run } from '../server/utils/run'
import { lockfileVulns } from '../server/utils/scanners'
import { planBumps } from '../server/utils/versions'

// Real fix of a vulnerable project with each package manager: lockfile, overrides, frozen install, Grype.
// Needs the network, corepack and grype in the PATH: pnpm test:e2e
const E2E = process.env.E2E === '1'

const PROJECTS: Record<string, { packageManager?: string, lockfile: string, workspace?: string }> = {
  'npm': { lockfile: 'package-lock.json' },
  'pnpm 9': { packageManager: 'pnpm@9.15.9', lockfile: 'pnpm-lock.yaml' },
  'pnpm 12': { packageManager: 'pnpm@12.15.0', lockfile: 'pnpm-lock.yaml', workspace: 'packages: []\n' },
  'Yarn 1': { packageManager: 'yarn@1.22.22', lockfile: 'yarn.lock' },
  'Yarn 4': { packageManager: 'yarn@4.18.1', lockfile: 'yarn.lock' },
}

const root = E2E ? mkdtempSync(join(tmpdir(), 'scanner-e2e-')) : ''
afterAll(() => {
  if (root) rmSync(root, { recursive: true, force: true })
})

async function exec(dir: string, cmd: string, args: string[], env: Record<string, string> = {}) {
  const result = await run(cmd, args, { cwd: dir, env, timeoutMs: 10 * 60_000 })
  if (result.code !== 0) throw new Error(`${cmd} ${args.join(' ')}: ${result.stdout.slice(-1000)}\n${result.stderr}`)
  return result.stdout
}

async function vulns(dir: string, m: Manager) {
  const out = await exec(dir, 'grype', [`dir:${dir}`, '--quiet', '--by-cve', '-o', 'json'], { GRYPE_CHECK_FOR_APP_UPDATE: 'false' })
  return lockfileVulns(JSON.parse(out), m.lockfile)
}

describe.skipIf(!E2E).each(Object.entries(PROJECTS))('fix with %s', (name, project) => {
  it('upgrades the vulnerable versions and keeps an installable lockfile', async () => {
    const dir = join(root, name.replace(' ', '-'))
    rmSync(dir, { recursive: true, force: true })
    mkdirSync(dir, { recursive: true })
    const pkg = { name: 'e2e', version: '1.0.0', private: true, packageManager: project.packageManager, dependencies: { express: '4.17.1' } }
    writeFileSync(join(dir, 'package.json'), `${JSON.stringify(pkg, null, 2)}\n`)
    if (project.workspace) writeFileSync(join(dir, 'pnpm-workspace.yaml'), project.workspace)
    // Yarn needs a yarn.lock to find the project root
    if (project.lockfile === 'yarn.lock') writeFileSync(join(dir, 'yarn.lock'), '')

    // The vulnerable starting point, generated by the manager itself
    const seed = project.packageManager?.startsWith('yarn@4') ? '__metadata:\n  version: 8\n' : 'lockfileVersion: \'9.0\'\n'
    const first = detectManager(pkg, file => file === project.lockfile ? seed : undefined)
    if ('error' in first) throw new Error(first.error)
    const cmd = managerCommands(first)
    await exec(dir, cmd.bin, cmd.lock, cmd.env)
    const read = (file: string) => existsSync(join(dir, file)) ? readFileSync(join(dir, file), 'utf8') : undefined
    const m = detectManager(pkg, read)
    if ('error' in m) throw new Error(m.error)
    expect(m.kind).toBe(first.kind)

    const before = await vulns(dir, m)
    const plan = planBumps(before, pkg)
    expect(plan.bumps.length).toBeGreaterThan(1)

    const next = applyBumps(m, { pkg, workspace: read('pnpm-workspace.yaml') }, read(m.lockfile)!, plan.bumps)
    writeFileSync(join(dir, 'package.json'), `${JSON.stringify(next.pkg, null, 2)}\n`)
    if (next.workspace) writeFileSync(join(dir, 'pnpm-workspace.yaml'), next.workspace)
    await exec(dir, cmd.bin, cmd.lock, cmd.env)
    await exec(dir, cmd.bin, cmd.verify, cmd.env)

    const after = await vulns(dir, m)
    const fixed = before.filter(v => !after.some(a => a.name === v.name && a.id === v.id))
    expect(fixed.length).toBeGreaterThan(before.length / 2)
    // corepack never pins a version on its own
    expect(JSON.parse(read('package.json')!).packageManager).toBe(project.packageManager)
  }, 15 * 60_000)
})
